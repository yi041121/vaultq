import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { authenticateRequest } from "@/lib/auth";
import { isSameOriginAuthRequest } from "@/lib/session-cookie";
import {
  buildPasswordResetUrl,
  createPasswordResetToken,
  hashPasswordResetToken,
  passwordResetExpiry,
} from "@/lib/password-reset";

type Ctx = { params: Promise<{ id: string }> };

// POST /api/accounts/:id/password-reset — admin generates a one-time reset
// link and delivers it out-of-band. This keeps password reset usable when
// email delivery is not configured, without ever storing the raw token.
export async function POST(request: NextRequest, { params }: Ctx) {
  const user = await authenticateRequest(request);
  if (!user) return NextResponse.json({ success: false, error: "Unauthorized" }, { status: 401 });
  if (user.role !== "ADMIN") return NextResponse.json({ success: false, error: "Admin only" }, { status: 403 });
  if (!isSameOriginAuthRequest(request)) {
    return NextResponse.json({ success: false, error: "Forbidden" }, { status: 403 });
  }

  const { id } = await params;
  if (!id || id.length > 128) {
    return NextResponse.json({ success: false, error: "Account not found" }, { status: 404 });
  }

  try {
    const target = await prisma.user.findUnique({
      where: { id },
      select: { id: true, name: true, email: true, isActive: true },
    });
    if (!target) return NextResponse.json({ success: false, error: "Account not found" }, { status: 404 });
    if (!target.isActive) {
      return NextResponse.json({ success: false, error: "Activate the account before resetting its password." }, { status: 409 });
    }

    const token = createPasswordResetToken();
    const tokenHash = hashPasswordResetToken(token);
    const expiresAt = passwordResetExpiry();

    await prisma.$transaction(async (tx) => {
      // Only the newest link stays valid, including links generated by email.
      await tx.passwordResetToken.deleteMany({ where: { userId: target.id } });
      await tx.passwordResetToken.create({ data: { userId: target.id, tokenHash, expiresAt } });
    });

    return NextResponse.json({
      success: true,
      data: {
        url: buildPasswordResetUrl(request.nextUrl.origin, token),
        expiresAt,
        name: target.name,
        email: target.email,
      },
    }, { headers: { "Cache-Control": "no-store" } });
  } catch (error) {
    console.error("Admin password reset link generation failed", error);
    return NextResponse.json({ success: false, error: "Could not generate a reset link. Please try again." }, { status: 500 });
  }
}
